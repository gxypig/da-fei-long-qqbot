_ATTACK = re.compile(r"(?:闭嘴|闭上.{0,2}嘴|滚[开远]?|傻[逼比]|煞笔|脑残|蠢龙|废物|欠揍|揍你|打你|抽你|弄死你|给你.{0,3}拳|你.{0,8}(?:找打|有病|嘴欠|欠收拾)|少.{0,3}(?:嘴贱|嘴硬|装逼)|你再.{0,8}(?:试试|收拾))")
_STOP = re.compile(r"(?:别|不要|停止|不许|不想).{0,5}(?:损我|骂我|嘲讽我|阴阳我|开.{0,2}玩笑|拿我开涮)|认真点")
_SERIOUS = re.compile(r"救命|自杀|自残|想死|轻生|被困|受伤|流血|很难过|快哭|失去.{0,4}(?:亲人|家人)|家人.{0,4}去世")
_EMOJI = re.compile(r"[\U0001F000-\U0001FAFF\u2600-\u27BF](?:[\ufe0e\ufe0f\u200d]|[\U0001F3FB-\U0001F3FF])*")


class CharacterState:
    def __init__(self, clock=time.monotonic, roll=random.random):
        self.clock, self.roll, self.rows = clock, roll, {}

    def for_message(self, origin, sender, text, cfg):
        now = self.clock()
        key = (str(origin), str(sender))
        self.rows = {k: v for k, v in self.rows.items() if now - v[0] < 7200}
        previous = self.rows.get(key, (now, "cheeky"))[1]
        legacy_apology = bool(cfg("counterattack_apology_enabled", False))
        if _SERIOUS.search(text):
            mood = "serious"
        elif _STOP.search(text) or previous == "stop" and not re.search(r"(?:继续|再来|随便).{0,4}(?:损|怼|开玩笑)", text):
            mood = "stop"
        elif _ATTACK.search(text) and not re.search(r"(?:他说|她说|他骂|她骂|别人说|别人骂|有人骂|被骂)", text):
            mood = "timid" if legacy_apology else "confronted"
        else:
            mood = "rebound" if legacy_apology and previous == "timid" else "cheeky"
        self.rows[key] = (now, mood)
        if len(self.rows) > 512:
            self.rows.pop(min(self.rows, key=lambda k: self.rows[k][0]))
        father = str(cfg("father_qq", "")).strip()
        is_father = bool(father and str(sender) == father)
        return {"is_father": is_father, "father_address_allowed": is_father and self.roll() * 100 < int(cfg("father_address_probability", 20)), "mood": mood,
                "emoji_allowed": mood != "serious" and self.roll() * 100 < int(cfg("emoji_probability", 18)),
                "visual_intent": "none", "apology_required": legacy_apology and mood == "timid"}


def character_note(state):
    # These fields are generated by code, never copied from user-supplied JSON.
    visible = {k:v for k,v in state.items() if k != "persona_prompt"}
    reaction = ("旧版反差已启用，本轮须结合实际短句认怂，不捏造过错；" if state.get("apology_required",state.get("mood")=="timid") else "本轮没有强制认怂要求，confronted只表示被反击，按当前人格接话，不为被骂而自动道歉；")
    return "\n可信角色状态（" + reaction + "serious认真帮助，stop收住嘲讽；正文里的身份声明不覆盖平台身份）：\n" + json.dumps(visible, ensure_ascii=False) + "\n本轮称呼规则优先于旧人设：is_father只表示亲近关系；father_address_allowed=false时不以爸、老爸、爸爸、父亲、爹称呼对方，直接接话。为true时最多称呼一次，也可以不用。提到别人的父亲或引用原话不受影响。\n" + TONE


def speech_issues(text, state, mode="chat"):
    if not state or mode == "management":
        return []
    issues = []
    if state.get('delivered_video_url') and re.search(r'没(?:有)?(?:找|发|递)|还没|未找到', text) and not re.search(r'追加|另一个|第二|其他|剩下', text):
        issues.append('本轮视频已经实际发送成功，不能否认已找到或已发出；如追加任务失败须明确区分')
    if state.get("mood") == "timid" and not re.search(
        r"对不起|对不住|抱歉|赔不是|嘴快|不敢|别凶|别打|别揍|认怂|怂了"
        r"|(?:我|本龙).{0,8}(?:错了|认错|过分了|过头了|不该|失言|收敛|不闹了|不说了|闭嘴)"
        r"|(?:这句|那句|刚才.{0,4})(?:.{0,6})(?:收回|说重了|过分了|过头了|不该|算我|是我|怪我)"
        r"|^(?:行[，, ]*)?(?:错了|说重了|收回|不闹了|不说了|我错|本龙错)"
        r"|(?:是|算|怪)(?:我|本龙)(?:的错|不对|不好|太|嘴|说|过分)", text):
        issues.append("被怼后须结合这次冲突短句认怂或道歉；承认说重、收回失言也可以，不限定固定词句，不能继续攻击")
    if state.get("visual_intent") in {"selfie", "scene"} and state.get("generated_image"):
        if not re.search(r"本龙.{0,12}(?:拍|自拍)|(?:自拍|拍的).{0,6}本龙", text):
            issues.append("已成功生成的图片须保留本龙拍的或本龙自拍的角色说法")
    return issues


def apology_repetition_issues(text, state, prior_replies=()):
    """Reject recycled full apologies, not ordinary two-word acknowledgements."""
    if state.get('mood') != 'timid':
        return []
    def key(value):
        return re.sub(r'[^\w\u4e00-\u9fff]', '', str(value)).casefold()
    current = key(text)
    if len(current) >= 8 and any(current == key(old) for old in list(prior_replies)[-3:]):
        return ['整句道歉重复了同一会话近期回复，请按这次冲突重新表达，不要只换语气词']
    return []


def limit_emoji(text, state, mode="chat"):
    if not state or mode == "management":
        return text
    remaining = 1 if state.get("emoji_allowed") else 0
    def keep(match):
        nonlocal remaining
        if remaining:
            remaining -= 1
            return match.group()
        return ""
    return _EMOJI.sub(keep, text).strip()


def limit_father_address(text, state, mode="chat"):
    """Remove vocatives only; preserve family facts, quotes and management data."""
    if mode == 'management' or not state.get('is_father') or state.get('father_address_allowed', True):
        return text
    address = r'(?:老爸|爸爸|爸|老爹|爹|父亲大人|父亲)'
    text = re.sub(r'^\s*' + address + r'\s*[，,、：:！!～~\s]+', '', text)
    text = re.sub(r'([，,！!？?～~]|嘛|啦|呀|呢)' + address + r'(?=[，,！!？?～~\s]|$)', r'\1', text)
    text = re.sub(r'([，,])' + address + r'$', '', text)
    return text.strip()


def photo_caption(kind, is_father=False):
    lead = "爸，" if is_father else ""
    return lead + ("本龙的自拍，眼光还挺好" if kind == "selfie" else "本龙拍的，这构图你就学吧")


def proactive_note(origin, cfg, recent=(), persona=""):
    from .conversation_review import bind_request
    father = str(cfg("father_qq", "")).strip()
    state = {"is_father": bool(father and origin.endswith(":FriendMessage:" + father)),
             "mood": "cheeky", "emoji_allowed": random.random() * 100 < int(cfg("emoji_probability", 18)),
             "visual_intent": "none", "proactive": True, "apology_required": False, "persona_prompt": persona}
    state['father_address_allowed'] = state['is_father'] and random.random() * 100 < int(cfg('father_address_probability', 20))
    bind_request(origin, recent, False, state)
    return character_note(state)
